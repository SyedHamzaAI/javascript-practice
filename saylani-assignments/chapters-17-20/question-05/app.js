// Chapters 17–20 — Question 5
// Print fruit names and their indexes

var fruits = ['apple', 'banana', 'mango', 'orange', 'strawberry'];
for (var i = 0; i < fruits.length; i++) { writeLine(fruits[i]); }
for (var j = 0; j < fruits.length; j++) {
    writeLine('Element at index ' + j + ' is ' + fruits[j]);
}
