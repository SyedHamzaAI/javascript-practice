// Chapters 6–9 — Question 1
// Compare prefix and postfix increment and decrement

var a = 10;
writeLine('The value of a is: ' + a);
writeLine('The value of ++a is: ' + (++a));
writeLine('Now the value of a is: ' + a);
writeLine('The value of a++ is: ' + (a++));
writeLine('Now the value of a is: ' + a);
writeLine('The value of --a is: ' + (--a));
writeLine('Now the value of a is: ' + a);
writeLine('The value of a-- is: ' + (a--));
writeLine('Now the value of a is: ' + a);
