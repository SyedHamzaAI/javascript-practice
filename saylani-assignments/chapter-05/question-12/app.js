// Chapters 5 — Question 12
// Calculate circle circumference and area

var radius = 20;
var pi = 3.142;
var circumference = 2 * pi * radius;
var area = pi * radius * radius;
writeLine('Radius of a circle: ' + radius);
writeLine('The circumference is ' + circumference.toFixed(2));
writeLine('The area is ' + area.toFixed(2));
