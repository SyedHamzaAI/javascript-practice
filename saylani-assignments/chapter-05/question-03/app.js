// Follow the increment and decrement sequence

var value;
writeLine('Value after variable declaration is: ' + value);
value = 5;
writeLine('Initial value: ' + value);
value++;
writeLine('Value after increment is: ' + value);
value += 7;
writeLine('Value after addition is: ' + value);
value--;
writeLine('Value after decrement is: ' + value);
writeLine('The remainder is: ' + (value % 3));
